import { chromium } from "playwright";
const S = "C:/Users/hayre/AppData/Local/Temp/integreat-shots";
const b = await chromium.launch();
const page = await b.newPage({ viewport: { width: 1280, height: 720 } });
await page.goto("http://localhost:5173", { waitUntil: "networkidle" });
await page.evaluate(() => localStorage.clear());
await page.reload({ waitUntil: "networkidle" });
await page.screenshot({ path: `${S}/p-00-import.png` });
await page.getByText("Wrong pin in the code").click();
await page.screenshot({ path: `${S}/p-01-modal.png` });
await page.getByRole("button", { name: "Load demo" }).click();
await page.waitForSelector(".graph-canvas", { timeout: 20000 });
await page.waitForTimeout(1200);
await page.screenshot({ path: `${S}/p-02-graph.png` });
await page.screenshot({ path: `${S}/p-03-topbar.png`, clip: { x: 0, y: 0, width: 1280, height: 80 } });
await page.getByText("Event flow", { exact: true }).first().click();
await page.waitForTimeout(1200);
await page.screenshot({ path: `${S}/p-04-flow.png` });
await page.setViewportSize({ width: 800, height: 600 });
await page.waitForTimeout(900);
await page.screenshot({ path: `${S}/p-05-800.png` });
console.log("done");
await b.close();
